/**
 * npm run db:generate
 * Writes prisma/schema.prisma and prisma/migrations/0002_real_schema/migration.sql from db/tables.ts.
 * Never edit those two files by hand - change db/tables.ts (or the item types in legacy/engine/schema.ts) and run this again.
 */
import * as fs from 'fs';
import * as path from 'path';
import { toPrismaModels, toSql } from './spec';
import { ALL_TABLES } from './tables';

const root = path.resolve(__dirname, '../..');

const HEADER = `// GENERATED by \`npm run db:generate\` from src/db/tables.ts. Do not edit by hand.

generator client {
  provider   = "prisma-client-js"
  engineType = "client"
}

datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}
`;

/** The old JSON tables. Kept (renamed in Prisma, same table names in Postgres) until \`npm run db:import-legacy\` has been run and 0003 drops them. */
const LEGACY = `
// ---------------------------------------------------------------- LEGACY (JSON) - to be dropped, see docs/DATABASE.md
model LegacyPortfolioMeta {
  id  Int  @id @default(1)
  reg Json

  @@map("PortfolioMeta")
}

model LegacyProduct {
  id        String   @id
  entry     Json
  meta      Json
  settings  Json
  counters  Json
  state     Json
  createdAt DateTime @default(now())
  updatedAt DateTime @updatedAt

  items LegacyItem[]
  links LegacyLink[]
  audit LegacyAuditEntry[]

  @@map("Product")
}

model LegacyItem {
  productId String
  id        String
  type      String
  phase     String
  status    String?
  title     String?
  rev       Int           @default(1)
  data      Json
  product   LegacyProduct @relation(fields: [productId], references: [id], onDelete: Cascade)

  @@id([productId, id])
  @@index([productId, type])
  @@index([productId, phase])
  @@map("Item")
}

model LegacyLink {
  productId String
  id        String
  type      String
  source    String
  target    String
  state     String        @default("valid")
  data      Json
  product   LegacyProduct @relation(fields: [productId], references: [id], onDelete: Cascade)

  @@id([productId, id])
  @@index([productId, source])
  @@index([productId, target])
  @@map("Link")
}

model LegacyAuditEntry {
  seq       BigInt        @id @default(autoincrement())
  productId String
  at        String
  action    String
  subject   String?
  actor     String?
  summary   String
  details   Json
  product   LegacyProduct @relation(fields: [productId], references: [id], onDelete: Cascade)

  @@index([productId, seq])
  @@map("AuditEntry")
}

model LegacyIdea {
  id   String @id
  data Json

  @@map("Idea")
}

// ---------------------------------------------------------------- REAL SCHEMA
`;

fs.writeFileSync(path.join(root, 'prisma/schema.prisma'), HEADER + LEGACY + '\n' + toPrismaModels(ALL_TABLES));
const dir = path.join(root, 'prisma/migrations/0002_real_schema');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'migration.sql'), `-- GENERATED by \`npm run db:generate\`. Creates the real relational schema (no JSON columns).\n-- The old JSON tables are left untouched; run \`npm run db:import-legacy\` to copy their data across.\n\n` + toSql(ALL_TABLES));
console.log(`wrote ${ALL_TABLES.length} tables`);
