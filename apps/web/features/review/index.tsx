'use client';
import Link from 'next/link';
import { useState } from 'react';
import type { FeatureProps } from '../types';
import { Badge, Card, Empty, ErrorBox, Loading, Page } from '@/components/ui';
import { Stat, useAction } from '@/components/kit';
import { api, useApi } from '@/lib/api';

const TYPES = ['Requirement', 'Story', 'AcceptanceCriterion', 'Flow', 'FlowStep', 'Problem', 'Question', 'Artifact'];
const RULE = 'AI and derived drafts do not count toward any gate until a person reviews them. “Accept” moves a draft to In review so it counts; “Reject” removes it from counting.';

/** Drafts to review: derived drafts wait here for a person. Prototype: review.js */
export default function Review({ pid, args }: FeatureProps) {
  return args[0] ? <Detail pid={pid} type={args[0]} /> : <Summary pid={pid} />;
}

function Count({ pid, type }: { pid: string; type: string }) {
  const { data } = useApi<any>(`/review/${type}`, pid);
  const n = data?.items?.length ?? 0;
  return <Link href={`/products/${pid}/review/${type}`} style={{ textDecoration: 'none', color: 'inherit' }}><Stat value={data ? n : '…'} label={`${type} drafts`} kind={n ? 'warn' : undefined} /></Link>;
}

function Summary({ pid }: { pid: string }) {
  return (
    <Page title="Drafts to review" sub="Everything generated by the system or an agent waits here for a person.">
      <div className="callout" style={{ marginBottom: 14 }}>{RULE}</div>
      <div className="grid g4">{TYPES.map((t) => <Count key={t} pid={pid} type={t} />)}<Link href={`/products/${pid}/checks`} style={{ textDecoration: 'none', color: 'inherit' }}><Stat value="→" label="Things to check (agent items)" /></Link></div>
    </Page>
  );
}

const sig = (r: any) => (r.type === 'Requirement' ? r.statement : r.type === 'Story' ? `${r.want || ''} | ${r.benefit || ''}` : r.type === 'AcceptanceCriterion' ? `${r.given || ''} | ${r.when || ''} | ${r.then || ''}` : null);
const sq = (t: any) => String(t || '').replace(/\s+/g, ' ').trim();

function Detail({ pid, type }: { pid: string; type: string }) {
  const { data, error, loading, reload } = useApi<any>(`/review/${encodeURIComponent(type)}`, pid);
  const [picked, setPicked] = useState<Set<string>>(new Set());
  const [edit, setEdit] = useState<any>(null);
  const act = useAction();
  if (loading) return <Loading />;
  if (error || !data) return <ErrorBox message={error || 'No data'} />;
  const items: any[] = data.items;
  const unchanged = (r: any) => typeof r.drafted_text === 'string' && sq(r.drafted_text) === sq(sig(r));
  const toggle = (id: string) => { const n = new Set(picked); n.has(id) ? n.delete(id) : n.add(id); setPicked(n); };
  const run = (status: string) => act.run(async () => {
    const kept = items.filter((i) => picked.has(i.id) && unchanged(i)).length;
    if (status === 'In review' && kept && !(await act.ask(`${kept} draft(s) are still exactly as the tool wrote them. Keep them as drafted? This is recorded and shows as a warning at sign-off.`, 'Keep as drafted'))) return;
    await api('/review', { method: 'POST', body: { ids: [...picked], status }, product: pid }); setPicked(new Set()); reload();
  });
  const saveEdit = () => act.run(async () => { await api(`/items/${edit.id}`, { method: 'PATCH', body: { fields: edit.fields }, product: pid }); setEdit(null); reload(); });
  const fields = (r: any) => (r.type === 'Requirement' ? [['statement', 'What the product must do']] : r.type === 'AcceptanceCriterion' ? [['given', 'Given'], ['when', 'When'], ['then', 'Then']] : r.type === 'Story' ? [['want', 'What they want'], ['benefit', 'Why']] : [['title', 'Title']]);
  return (
    <Page title={`Review: ${type}`} sub={`${items.length} derived draft(s) waiting.`} right={<Link className="btn" href={`/products/${pid}/review`}>All types</Link>}>
      <div className="callout" style={{ marginBottom: 12 }}>{RULE}</div>
      {items.length === 0 ? <Empty>No derived {type} drafts. Nothing to review here.</Empty> : (
        <Card flush>
          <div className="row" style={{ padding: 10 }}><label><input type="checkbox" checked={picked.size === items.length} onChange={(e) => setPicked(e.target.checked ? new Set(items.map((i) => i.id)) : new Set())} /> Select all</label><span className="small muted">{picked.size} selected</span><span className="spacer" />
            <button className="btn primary sm" disabled={!picked.size || act.busy} onClick={() => run('In review')}>Accept (move to In review)</button><button className="btn danger sm" disabled={!picked.size || act.busy} onClick={() => confirm(`Reject ${picked.size} draft(s)?`) && run('Rejected')}>Reject</button></div>
          {act.box}
          <table className="tbl compact"><tbody>{items.map((r) => (
            <tr key={r.id}><td><input type="checkbox" checked={picked.has(r.id)} onChange={() => toggle(r.id)} /></td><td className="mono xs"><Link href={`/products/${pid}/item/${r.id}`}>{r.id}</Link></td>
              <td>{r.title} {unchanged(r) && <Badge kind="warn">Draft, needs your rewrite</Badge>}<div className="xs muted">{sig(r)}</div></td>
              <td><button className="btn ghost sm" onClick={() => setEdit({ id: r.id, fields: Object.fromEntries(fields(r).map(([k]) => [k, ''])), draft: r, defs: fields(r) })}>Rewrite</button></td></tr>
          ))}</tbody></table>
        </Card>
      )}
      {edit && (
        <div className="modal-bg" style={{ position: 'fixed', zIndex: 50 }} onClick={() => setEdit(null)}><div className="modal" onClick={(e) => e.stopPropagation()}>
          <div className="modal-h"><h2>Rewrite in your own words</h2><button className="btn sm ghost" onClick={() => setEdit(null)}>Close</button></div>
          <div className="modal-b">{edit.defs.map(([k, label]: string[]) => <div key={k} style={{ marginBottom: 10 }}><label className="strong">{label}</label><textarea rows={2} style={{ width: '100%' }} value={edit.fields[k]} onChange={(e) => setEdit({ ...edit, fields: { ...edit.fields, [k]: e.target.value } })} /><div className="xs muted"><b>Draft:</b> {edit.draft[k]}</div></div>)}
            <button className="btn primary" disabled={Object.values(edit.fields).some((v: any) => !String(v).trim()) || act.busy} onClick={saveEdit}>Save (it now counts)</button></div>
        </div></div>
      )}
    </Page>
  );
}
